BLUEMAP_VERSION = "5.16"
BLUEMAP_URL = "https://github.com/BlueMap-Minecraft/BlueMap/releases/download/v5.16/bluemap-5.16-cli.jar"
BLUEMAP_SHA256 = "7940d561890373897f8f6be91a52e765461f40e5be4e1c4401004073ee0d2580"
